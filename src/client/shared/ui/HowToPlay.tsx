import type { ReactNode } from 'react';
import type { GameSnapshot } from '../../../shared/protocol.js';
import styles from './GameDialog.module.css';

function Chapter({ number, title, children }: { number: string; title: string; children: ReactNode }) {
  return <details className={styles.guideChapter}>
    <summary><span className={styles.chapterNumber} aria-hidden="true">{number}</span><span>{title}</span></summary>
    <div className={styles.chapterBody}>{children}</div>
  </details>;
}

export function HowToPlay({ game }: { game: GameSnapshot }) {
  const { base, zones, dwelling, mode } = game.venue;
  const ordinary = mode === 'ordinary';
  const { searchSeconds } = game.settings;
  const searchDuration = searchSeconds % 60 === 0 ? `${searchSeconds / 60} мин.` : `${searchSeconds} сек.`;
  return <div className={styles.guide}>
    <div className={styles.guideIntro}>
      <p className={styles.guideMode}>{ordinary ? 'Обычная партия' : 'Первая партия'} · Правила компьютерной версии</p>
      <p><strong>Цель игры.</strong> Вы — медиумы. Освобождайте одержимых и выполняйте миссии, чтобы открыть три прорицания и снять с доски все свечи к концу седьмого раунда.</p>
    </div>

    <Chapter number="01" title="Подготовка к игре">
      <h3>Игровые локации</h3>
      <p><q>Выберите место, знакомое всем игрокам.</q> В помещении договоритесь, в какие комнаты можно заходить. На улице обозначьте границы каждой локации. Выберите столько локаций, чтобы их было примерно вдвое меньше, чем медиумов.</p>
      <p>Устройте ритуальный стол у ноутбука. Это ваша <strong>база</strong>. Выберите пустое место для <strong>Обители духов</strong> в одной из разрешённых локаций. Подойдёт дальний угол дома или место, которое кажется вам самым таинственным. Оставьте его пустым.</p>
      <p>Укажите эти места в <strong>«Настройках партии»</strong>. Там же можно добавить карты для помещения или улицы, карты с физическим контактом, более сложные и смешные карты.</p>
      <ul>
        <li><strong>База.</strong> {base}.</li>
        <li><strong>Разрешённые локации.</strong> {zones.length ? zones.join(', ') : 'Организатор ещё не указал локации'}.</li>
        <li><strong>Обитель духов.</strong> {dwelling ? `${dwelling.zone}, ${dwelling.place}` : 'Организатор ещё не указал место'}.</li>
      </ul>
      <h3>Ритуальный стол</h3>
      <p>Соберите от 5 до 12 медиумов. Каждый, включая организатора, входит в комнату с телефона по QR или коду. Компьютер играет роль Великого Мастера. Он раздаёт карты, подаёт сигналы и ведёт ритуал на общем экране.</p>
      <p>Мастер кладёт на доску рубашкой вверх два случайных прорицания и карту с дверью. В ячейке <strong>А</strong> свечей на одну больше, чем медиумов. В <strong>Б</strong> две свечи, в <strong>В</strong> три. Например, если вас шестеро, Мастер поставит семь свечей на А.</p>
      <h3>Источник освещения</h3>
      <p>У каждого медиума свой источник света. Приглушите общий свет и убавьте яркость экрана телефона. Оставьте достаточно света, чтобы читать карту и видеть дорогу. Яркий фонарик телефона оставьте выключенным.</p>
    </Chapter>

    <Chapter number="02" title="Фаза подготовки">
      <p>Раунд состоит из трёх фаз. Сначала подготовьтесь, затем проведите экзорцизм и проверьте его итог. Партия длится до семи раундов.</p>
      <ol>
        <li>Перед первым раундом откройте <strong>«Сюжет»</strong> на ноутбуке и прочитайте пролог вслух.</li>
        <li>Мастер случайно распределяет роли между медиумами, получающими карты. Если их нечётное число, экзорцистов на одного больше. Ноутбук показывает роли, а задания видны только на личных телефонах.</li>
        <li>Прочитайте свою карту втайне и нажмите <strong>«Готов»</strong>. Времени на чтение сколько нужно. Если задание вам не подходит, до старта нажмите <strong>«Заменить карточку»</strong>.</li>
        <li>Когда организатор запустит раунд, новые одержимые уходят с базы. У них <strong>{game.settings.placementSeconds} сек.</strong>, чтобы занять место, отметить его в поле <strong>«Ваша локация»</strong> и погасить свет. Неосвобождённые группы остаются там же. Экзорцисты ждут сигнала к поиску у ритуального стола.</li>
      </ol>
    </Chapter>

    <Chapter number="03" title="Фаза экзорцизма">
      <p>Мастер даёт сигнал к поиску. На телефоне этот этап называется «Изгнание». Поиск длится до <strong>{searchDuration}</strong> Организатор может дать призыв раньше.</p>
      <h3>Одержимые</h3>
      <p><q>Каждый одержимый должен выполнить то, что указано на его карте миссии.</q> Оставайтесь на своём месте с погашенным светом и разыгрывайте ситуацию из карты. Условия заражения и освобождения держите в тайне.</p>
      <h3>Экзорцисты</h3>
      <p><q>Основная цель экзорциста — найти одержимого и освободить его.</q> Ходите по одному и держите тусклый свет включённым. При встрече можно обменяться парой слов, затем продолжайте поиски поодиночке. До призыва оставайтесь в игровых локациях{ordinary && ', если Мастер не велел вам вернуться раньше'}.</p>
      <p>При желании выполните личную миссию. Успейте до призыва и отметьте выполнение в разделе <strong>«Миссии»</strong>. Для подношения лично дойдите до Обители духов и выполните действие из карты.</p>
      {ordinary && <>
        <h3>Испытание Великого Мастера</h3>
        <p>На раунд Мастер берёт одно испытание. Если он даст вам поручение, прочитайте его в разделе <strong>«Миссии»</strong> и держите в тайне. Если Мастер обратится к вам за подтверждением, сообщите только то, что сделали или заметили сами.</p>
      </>}
      <h3>Освобождение одержимого</h3>
      <p>Одержимый решает, выполнил ли экзорцист условие его карты. Если выполнил, поблагодарите его и скажите, что вы свободны.</p>
      <p>Экзорцист нажимает <strong>«Освободить»</strong>, выбирает группу по именам и подтверждает освобождение. Если в той же отмеченной локации есть другая группа с той же картой, она тоже свободна. Все освобождённые включают свет и сразу идут к ритуальному столу. По дороге они больше не участвуют в поиске.</p>
      <h3>Заражение экзорциста</h3>
      <p>Если экзорцист выполнил условие заражения, сообщите ему об этом и отметьте его имя через <strong>«Заразить»</strong>. Теперь он гасит свет, остаётся с вашей группой и разыгрывает ту же ситуацию. Если его телефон ещё не показал новую карту, объясните ему задание или покажите свою карту.</p>
      <p>Миссия заражённого экзорциста в этом раунде не засчитывается, даже если он выполнил её до заражения или впоследствии освободился.</p>
    </Chapter>

    <Chapter number="04" title="Фаза проверки">
      <p>По призыву Мастера свободные медиумы сразу идут к ритуальному столу. Одержимые и заражённые, которых не освободили, остаются на своих местах с прежними картами.</p>
      <p>Организатор открывает <strong>сверку</strong> на ноутбуке. Телефоны передают отметки о заражениях, освобождениях и миссиях. Если связь пропала или в отметках есть ошибка, сообщите организатору, что произошло. После сверки он подтверждает итог.</p>
      <p>Мастер двигает одну свечу на один шаг за каждый успех.</p>
      <ul>
        <li>За каждую освобождённую группу. Заражённые внутри группы не дают дополнительных шагов.</li>
        <li>За каждую выполненную миссию экзорциста, которого в этом раунде не заразили.</li>
        {ordinary && <li>За испытание Мастера, если его результат даёт дополнительный шаг.</li>}
      </ul>
      <p>Свечи движутся слева направо. Сначала Мастер перемещает все свечи из А в Б. Затем переносит их из Б в В и только после этого снимает с доски.</p>
      <p>К следующей раздаче допускаются те, чьё возвращение на базу подтверждено. Если вернулся один медиум, он получает карту экзорциста.</p>
    </Chapter>

    <Chapter number="05" title="Карты прорицания">
      <p>После проверки Мастер открывает карты по порядку, когда на них больше нет свечей. Первое прорицание вводит правило для всех медиумов у ритуального стола. Второе действует вместе с первым. Последняя карта открывает дверь и завершает ритуал.</p>
      <h3>Возвращение свечи</h3>
      <p>Если ваше возвращение подтверждено, сообщить о нарушении можно со своего телефона во время сверки или чтения новой карты. Откройте <strong>«Открытые прорицания и свечи»</strong> и выберите <strong>«Доклады о прорицаниях»</strong>.</p>
      <p>За подтверждённое нарушение Мастер возвращает одну свечу на шаг влево из самой большой стопки. Если больше всего свечей уже снято с доски, одна из них возвращается в В. Если самая большая стопка находится в А или несколько стопок равны по наибольшему числу свечей, шаг пропускается. Открытые прорицания продолжают действовать.</p>
    </Chapter>

    <Chapter number="06" title="Конец игры">
      <ul>
        <li><strong>Победа.</strong> К концу седьмого раунда все прорицания открыты и все свечи сняты.</li>
        <li><strong>Поражение.</strong> После проверки седьмого раунда на доске остались свечи или никто из медиумов не смог вернуться к ритуальному столу.</li>
      </ul>
      <p>Если у кого-то пропала связь, Мастер может ждать возвращения до {game.settings.offlineWaitSeconds ?? 90} сек. после призыва. Если есть спорная отметка об освобождении, итог может подождать до сверки.</p>
      <p>При победе, поражении или остановке партии все медиумы возвращаются на базу.</p>
    </Chapter>

    <Chapter number="07" title="Дополнительные сведения">
      <p>Передвигайтесь шагом и оставляйте проходы свободными. Касайтесь других участников только с их согласия.</p>
      <p>Во время паузы прекратите игровые действия и остановитесь в безопасном месте. Мастер сообщит, когда можно продолжать.</p>
      <p>В любой момент можно выйти из роли, попросить о помощи, отказаться от прикосновения или остановить игру. Просьба о помощи и технические сообщения не считаются игровыми действиями.</p>
    </Chapter>

    <p><a href="https://nizagams.ru/rules/oderzhimye/" target="_blank" rel="noopener noreferrer">Полные правила настольной игры у издателя (PDF)</a></p>
  </div>;
}
