import type { GameSnapshot } from '../../../shared/protocol.js';
import styles from './GameDialog.module.css';

export function HowToPlay({ game, compact = false }: { game: GameSnapshot; compact?: boolean }) {
  const { base, zones, dwelling, mode } = game.venue;
  return <div className={styles.guide} aria-label="Правила этой партии">
    <p><strong>Цель игры:</strong> снять все свечи за семь раундов или быстрее.</p>

    <details>
      <summary>Перед первым раундом</summary>
      <p><strong>База</strong> — место сбора у общего экрана. В этой партии это «{base}».</p>
      <p><strong>Игровые локации</strong> — места, где разрешён поиск. {zones.length ? zones.join(', ') + '.' : 'Организатор ещё их не указал.'}</p>
      <p><strong>Обитель</strong> — пустое место для заданий.{dwelling && ` В этой партии: ${dwelling.zone}, ${dwelling.place}.`} Реквизит не нужен.</p>
      {!compact && <p>Играют от пяти до двенадцати человек. Каждый, включая организатора, входит с телефона по коду комнаты или QR. Роли распределяются случайно. При нечётном числе получателей экзорцистов на одного больше. Исходные роли видны на ноутбуке.</p>}
      <p>Прочитайте личную карточку и <strong>отметьте готовность</strong>. Неудобную карточку можно попросить заменить до старта.</p>
      {!compact && <p>Чтение без таймера. Организатор запускает раунд с ноутбука, который показывает этапы, время и общий счёт.</p>}
    </details>

    <details>
      <summary>Как играть за одержимого</summary>
      <p><strong>Одержимый</strong> — игрок, который повторяет поведение из карточки и ждёт освобождения.</p>
      <ol>
        <li><strong>Расстановка</strong> — {game.settings.placementSeconds} сек. на выбор места. Если вы только получили роль, отметьте свою локацию на телефоне и погасите или закройте свет на месте. Если вы остались с группой с прошлого раунда, оставайтесь там же.</li>
        <li>Во время поиска оставайтесь там и повторяйте поведение из карточки. Держите условия заражения и освобождения в секрете.</li>
        <li><strong>Заражение.</strong> Если экзорцист выполнил условие заражения из карточки, скажите ему об этом и отметьте его в окне «Заразить». Он присоединится к вашей группе и будет повторять ваше поведение.</li>
        <li><strong>Освобождение.</strong> Когда экзорцист выполнит ваше условие, он отметит освобождение на своём телефоне. Включите свет и всей группой сразу идите на базу. По пути больше не участвуйте в поиске.</li>
      </ol>
      {!compact && <p>Если в одной отмеченной локации две группы с одинаковой карточкой, освобождаются обе.</p>}
      <p><strong>Если вас не освободили</strong>, оставайтесь на месте с той же группой и карточкой.</p>
    </details>

    <details>
      <summary>Как играть за экзорциста</summary>
      <p><strong>Экзорцист</strong> — игрок, который ищет и освобождает одержимых.</p>
      <ol>
        <li><strong>Дождитесь сигнала на базе.</strong> Поиск длится до {game.settings.searchSeconds} сек. Ходите по одному, шагом и с приглушённым светом.</li>
        <li>Наблюдайте за одержимым и попробуйте угадать, какое действие освободит его. Это <strong>условие освобождения</strong>. Оно написано на личной карточке одержимого. Свободным экзорцистам её не показывают.</li>
        <li><strong>Если вас заразили</strong>, погасите свет, прочитайте карточку группы и повторяйте её поведение. Заражение отмечает одержимый. При потере связи сверяйте отметки с организатором на базе.</li>
      </ol>
      <p><strong>Освободить.</strong> Отметьте по именам тех, чьё условие вы выполнили. Вместе с каждым освободится вся его группа.</p>
      {!compact && <p>При встрече можно ненадолго заговорить.</p>}
      <p><strong>Личная миссия</strong> — необязательное задание на вашей карточке. Выполните её до призыва и отметьте в окне «Миссии». После заражения миссия этого раунда не засчитывается, даже если вас освободили.</p>
      {mode === 'ordinary' && <p><strong>Испытание Мастера</strong> — дополнительное поручение, которое игра может выдать свободному экзорцисту. Следуйте инструкции в окне «Миссии». Если вас попросят подтвердить событие, отвечайте за себя.</p>}
    </details>

    <details>
      <summary>Когда возвращаться на базу</summary>
      <p><strong>Призыв</strong> — сигнал конца поиска. Свободные идут на базу. Одержимые и заражённые, которых не освободили, остаются на месте.</p>
      <p><strong>Сверка</strong> — проверка записей раунда. Телефоны со связью передают статус автоматически. Если связи нет, сообщите организатору, вернулись ли вы, были заражены или освобождены.</p>
      {!compact && <p>Организатор разбирает спорные и поздние записи, затем подтверждает итог.</p>}
      <p>Новую карточку получают только те, чьё возвращение на базу подтвердили.{!compact && ' Если вернулся один игрок, он становится экзорцистом.'}</p>
    </details>

    <details>
      <summary>Свечи, прорицания и конец игры</summary>
      <p><strong>Ритуал</strong> — общий счёт на доске со свечами. После сверки за каждую освобождённую исходную карточку и зачтённую миссию одна свеча сдвигается на шаг. {mode === 'ordinary' && 'Испытание Мастера может дать ещё один шаг.'}</p>
      {!compact && <p>В стопке А на одну свечу больше, чем игроков. В Б две свечи, в В три. За освобождение исходной карточки засчитывается один шаг, даже если в группе несколько заражённых.</p>}
      <p><strong>Прорицания</strong> — правила, которые открываются, когда стопки свечей пустеют по очереди. Они действуют на базе. За подтверждённое нарушение свеча может вернуться на шаг.</p>
      {compact && <p>Если ваше возвращение на базу подтвердили, сообщите о нарушении на сверке или при чтении новой карточки. Кнопка находится в разделе «Открытые прорицания и свечи».</p>}
      {!compact && <>
        <p>Первые два прорицания добавляют правила, третье открывает финальную дверь. Открытые правила действуют вместе и сохраняются после штрафа. Игроки, чьё возвращение на базу подтверждено, могут сообщить о нарушении на сверке или при чтении следующей карточки.</p>
        <p>Свеча возвращается из самой большой стопки, включая снятые свечи. Если самая большая стопка — А или две стопки делят первое место, свеча остаётся на месте.</p>
      </>}
      <p>Если на связи остались только одержимые и заражённые, игра ждёт свободных без связи до {game.settings.offlineWaitSeconds ?? 90} сек. с призыва. Если никто не вернулся и спорные отметки разобраны, партия заканчивается поражением.</p>
      <p><strong>Победа</strong> — все свечи сняты. <strong>Поражение</strong> — после седьмой сверки свечи остались или подтвердилось, что все оставшиеся игроки одержимы или заражены. Когда игра закончилась или её остановили, <strong>на базу идут все</strong>.</p>
    </details>

    <details>
      <summary>Пауза и помощь</summary>
      <p><strong>На паузе</strong> остановитесь в безопасном месте. В любой момент можно выйти из роли, попросить помощи, отказаться от прикосновения или остановить игру. За это нет заражения или штрафа.</p>
      <p>Касайтесь других только с согласия. Держите проходы свободными.</p>
    </details>
  </div>;
}
