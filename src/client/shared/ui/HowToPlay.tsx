import type { ReactNode } from 'react';
import type { GameSnapshot } from '../../../shared/protocol.js';
import styles from './GameDialog.module.css';

function Chapter({ number, title, children }: { number: string; title: string; children: ReactNode }) {
  return <details className={styles.guideChapter}>
    <summary><span className={styles.chapterNumber} aria-hidden="true">{number}</span><span>{title}</span></summary>
    <div className={styles.chapterBody}>{children}</div>
  </details>;
}

export function HowToPlay({ game }: { game: GameSnapshot }) {
  const { base, zones, dwelling, mode } = game.venue;
  const ordinary = mode === 'ordinary';
  const { searchSeconds } = game.settings;
  const searchDuration = searchSeconds % 60 === 0 ? `${searchSeconds / 60} мин.` : `${searchSeconds} сек.`;
  return <div className={styles.guide}>
    <div className={styles.guideIntro}>
      <p className={styles.guideMode}>{ordinary ? 'Обычная партия' : 'Первая партия'} · Правила игры</p>
      <p><strong>Ваша общая цель — снять все свечи за семь раундов.</strong> Освобождайте одержимых и выполняйте миссии, чтобы очистить это место от духов.</p>
    </div>

    <Chapter number="01" title="Подготовка к партии">
      <p>Играют от 5 до 12 человек. Соберитесь у ноутбука: это ваша <strong>база</strong>, место для сверки и ритуала. Каждый, включая организатора, входит с телефона по коду комнаты или QR.</p>
      <p>Компьютер берёт на себя роль Великого Мастера: раздаёт карточки, подаёт сигналы и ведёт счёт. Перед первой раздачей прочитайте «Сюжет» на ноутбуке.</p>
      <ul>
        <li><strong>База:</strong> {base}.</li>
        <li><strong>Где можно искать:</strong> {zones.length ? zones.join(', ') : 'договоритесь о границах с организатором'}.</li>
        <li><strong>Обитель духов</strong> — пустое место для заданий. {dwelling && <>В этой партии: {dwelling.zone}, {dwelling.place}. </>}Ничего класть туда не нужно.</li>
      </ul>
      <p>Приглушите свет так, чтобы видеть дорогу. Убавьте яркость экранов и ходите шагом по разрешённым местам.</p>
    </Chapter>

    <Chapter number="02" title="Карточки и расстановка">
      <p>Компьютер случайно делит игроков на одержимых и экзорцистов. Если карточек нечётное число, экзорцистов на одного больше. Роли на момент раздачи видны на ноутбуке, а задания каждый читает втайне.</p>
      <ol>
        <li>Прочитайте карточку и нажмите <strong>«Готов»</strong>. Если задание вам не подходит, до старта нажмите <strong>«Заменить карточку»</strong>. На чтение нет таймера.</li>
        <li>Организатор запускает раунд с ноутбука. У новых одержимых <strong>{game.settings.placementSeconds} сек.</strong>, чтобы занять место, выбрать его в поле <strong>«Ваша локация»</strong> и погасить свет. Группы с прошлого раунда остаются на своих местах.</li>
        <li>Экзорцисты ждут начала поиска на базе.</li>
      </ol>
    </Chapter>

    <Chapter number="03" title="Поиск и личные миссии">
      <p>Поиск длится до <strong>{searchDuration}</strong> О начале и конце сообщает ноутбук.</p>
      <h3>Одержимые</h3>
      <p>Оставайтесь на выбранном месте с погашенным светом. Разыграйте ситуацию из карточки. Держите условия освобождения и заражения в секрете.</p>
      <h3>Экзорцисты</h3>
      <p>Ищите по одному, с приглушённым светом. При встрече можно коротко поговорить. Наблюдайте за одержимым и попробуйте понять, какое действие его освободит. Возвращайтесь на базу по призыву{ordinary && ', если поручение Мастера не говорит иначе'}.</p>
      <p><strong>Личная миссия</strong> необязательна. Выполните её до призыва и отметьте в разделе <strong>«Миссии»</strong>. Если карточка просит сделать подношение, лично дойдите до Обители и выполните указанное действие.</p>
      {ordinary && <p><strong>Испытание Мастера.</strong> Компьютер может дать свободному экзорцисту тайное поручение в разделе <strong>«Миссии»</strong>. Следуйте подсказкам на телефоне. Если вас попросят подтвердить событие, отвечайте только за себя.</p>}
    </Chapter>

    <Chapter number="04" title="Освобождение и заражение">
      <h3>Если условие освобождения выполнено</h3>
      <ol>
        <li>Одержимый говорит экзорцисту, что у него получилось.</li>
        <li>Экзорцист нажимает <strong>«Освободить»</strong>, выбирает тех, чьё условие выполнил, и подтверждает выбор.</li>
        <li>Вся освобождённая группа включает свет и сразу идёт на базу. По пути она больше не участвует в поиске.</li>
      </ol>
      <p>Если в одной отмеченной локации две группы с одинаковой карточкой, освобождаются обе.</p>
      <h3>Если сработало условие заражения</h3>
      <p>Тот, чьё условие сработало, говорит экзорцисту об этом и отмечает его по имени через <strong>«Заразить»</strong>.</p>
      <p>Когда вас заразили, погасите свет и разыгрывайте ту же ситуацию вместе с группой. На телефоне появится «Вы заражены» и карточка группы. Если карточка не обновилась, прочитайте её у того, кто вас заразил.</p>
      <p>Личная миссия заражённого экзорциста в этом раунде не засчитывается, даже если он успел её выполнить и потом освободился.</p>
    </Chapter>

    <Chapter number="05" title="Призыв и сверка">
      <p>По призыву все свободные идут на базу. Кто остался одержимым или заражённым, остаётся в своей локации с той же группой и карточкой.</p>
      <p>На <strong>сверке</strong> организатор проверяет отметки и подтверждает итог. Телефоны на связи передают отметки сами. Если связи нет или в записях ошибка, сообщите организатору, что произошло.</p>
      <p>В следующем раунде карточки получают только те, чьё возвращение на базу подтверждено. Если вернулся один игрок, он становится экзорцистом.</p>
    </Chapter>

    <Chapter number="06" title="Свечи, прорицания и финал">
      <p>В начале партии в стопке <strong>А</strong> на одну свечу больше, чем игроков, в <strong>Б</strong> две свечи, в <strong>В</strong> три. После сверки за каждый успех компьютер передвигает одну свечу на шаг: А → Б → В → с доски.</p>
      <ul>
        <li><strong>Освобождение:</strong> один шаг за каждую освобождённую группу, сколько бы заражённых в ней ни было.</li>
        <li><strong>Личная миссия:</strong> один шаг за каждую зачтённую миссию.</li>
        {ordinary && <li><strong>Испытание Мастера:</strong> может дать один дополнительный шаг.</li>}
      </ul>
      <h3>Открытые прорицания</h3>
      <p>Когда стопки пустеют по очереди, открываются <strong>прорицания</strong>. Первые два добавляют правила, которые действуют вместе на базе. Третье открывает финальную дверь.</p>
      <p>Если ваше возвращение подтверждено, о нарушении можно сообщить с телефона в разделе <strong>«Открытые прорицания и свечи»</strong> во время сверки или чтения следующей карточки.</p>
      <p>За подтверждённое нарушение одна свеча возвращается на шаг из самой большой стопки, включая снятые свечи. Если больше всего свечей в А или несколько стопок делят первое место, свечи не двигаются. Открытые правила остаются в силе.</p>
      <h3>Конец партии</h3>
      <p><strong>Победа:</strong> все свечи сняты. <strong>Поражение:</strong> после седьмого раунда свечи ещё на доске или никто не смог вернуться на базу.</p>
      <p>Если связь пропала, игра может ждать возвращения до {game.settings.offlineWaitSeconds ?? 90} сек. после призыва. Спорная отметка об освобождении может отложить итог до сверки.</p>
      <p>Когда партия заканчивается, на базу возвращаются все.</p>
    </Chapter>

    <Chapter number="07" title="Пауза и помощь">
      <p>По сигналу паузы прекратите игровые действия и остановитесь в безопасном месте. Ноутбук сообщит, когда можно продолжать.</p>
      <p>Можно в любой момент выйти из роли, попросить помощи, отказаться от прикосновения или остановить игру. За это нет заражения или штрафа. Касайтесь других только с их согласия и оставляйте проходы свободными.</p>
    </Chapter>
  </div>;
}
